#include <iostream>
using namespace std;
int main() {
    int a = 3, b = 5, c = 12;
    double arithmetic_mean = (a + b + c) / 3.0;
    cout << "Arithmetic Mean is: " << arithmetic_mean << endl;

    return 0;
}